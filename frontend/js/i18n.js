let currentLang = localStorage.getItem("fechat_lang") || "pt_BR";
function t(key) {
  const dict = translations[currentLang] || translations.pt_BR;
  return dict[key] || key;
}
function setLanguage(lang) {
  if (translations[lang]) {
    currentLang = lang;
    localStorage.setItem("fechat_lang", lang);
    applyTranslations();
  }
}
function applyTranslations() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    el.textContent = t(key);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    el.placeholder = t(key);
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const key = el.getAttribute("data-i18n-title");
    el.title = t(key);
  });
}
function formatLastSeen(dateInput, isOnline = false) {
  const isPt = currentLang === "pt_BR";
  if (isOnline) {
    return isPt ? "Online agora" : "Online now";
  }
  if (!dateInput) {
    return isPt ? "Visto há muito tempo..." : "Last seen a long time ago...";
  }
  const date = new Date(dateInput);
  if (isNaN(date.getTime())) {
    return isPt ? "Visto há muito tempo..." : "Last seen a long time ago...";
  }
  const now = new Date();
  const diffSec = Math.floor((now.getTime() - date.getTime()) / 1e3);
  if (diffSec < 60) {
    return isPt ? "Visto há menos de 1 minuto" : "Last seen just now";
  }
  if (diffSec < 120) {
    return isPt ? "Visto há 1 minuto" : "Last seen 1 minute ago";
  }
  if (diffSec < 3600) {
    const mins = Math.floor(diffSec / 60);
    return isPt ? `Visto há ${mins} minutos` : `Last seen ${mins} minutes ago`;
  }
  if (diffSec < 7200) {
    return isPt ? "Visto há 1 hora" : "Last seen 1 hour ago";
  }
  if (diffSec < 86400) {
    const hours = Math.floor(diffSec / 3600);
    const timeStr = date.toLocaleTimeString([], {
      hour: "2-digit",
      minute: "2-digit",
    });
    return isPt ? `Visto hoje às ${timeStr}` : `Last seen today at ${timeStr}`;
  }
  if (diffSec < 172800) {
    const timeStr = date.toLocaleTimeString([], {
      hour: "2-digit",
      minute: "2-digit",
    });
    return isPt
      ? `Visto ontem às ${timeStr}`
      : `Last seen yesterday at ${timeStr}`;
  }
  if (diffSec < 604800) {
    const days = Math.floor(diffSec / 86400);
    return isPt ? `Visto há ${days} dias` : `Last seen ${days} days ago`;
  }
  if (diffSec < 1209600) {
    return isPt ? "Visto na última semana" : "Last seen last week";
  }
  if (diffSec < 2592e3) {
    const weeks = Math.floor(diffSec / 604800);
    return isPt ? `Visto há ${weeks} semanas` : `Last seen ${weeks} weeks ago`;
  }
  if (diffSec < 5184e3) {
    return isPt ? "Visto no último mês" : "Last seen last month";
  }
  return isPt ? "Visto há muito tempo..." : "Last seen a long time ago...";
}
